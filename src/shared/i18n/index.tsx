const Context = createContext({ locale: 'en', setLocale: (_: string) => {}, t: en });
export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState('en');
  return (
    <Context.Provider value={{ locale, setLocale, t: locale === 'sq' ? sq : en }}>
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
